import org.jetbrains.kotlin.gradle.plugin.mpp.DisableCacheInKotlinVersion
import org.jetbrains.kotlin.gradle.plugin.mpp.KotlinNativeTarget

plugins {
    id("ostrom.kmp")
}

// The version printed by `ostrom version`, written into a generated source at build time.
val generatedBuildInfo = layout.buildDirectory.dir("generated/build-info")
val generateBuildInfo by tasks.registering {
    val version = project.version.toString()
    // The PostHog project key of the official builds (a public, write-only key): blank in local builds, which then
    // never send usage statistics, even when turned on.
    val postHogKey = providers.gradleProperty("ostromPosthogKey").orElse("").get()
    // Written into a Kotlin string literal: only the characters a PostHog key has, so nothing can break or inject.
    require(Regex("[A-Za-z0-9_-]*").matches(postHogKey)) { "ostromPosthogKey has characters a PostHog key never has" }
    val output = generatedBuildInfo
    inputs.property("version", version)
    inputs.property("postHogKey", postHogKey)
    outputs.dir(output)
    doLast {
        val file = output.get().file("dev/ostrom/cli/BuildInfo.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package dev.ostrom.cli
            |
            |/** Facts about this build of the CLI, generated by Gradle. */
            |// coverage: generated constants, inlined where read; the object itself is never loaded.
            |@dev.ostrom.cli.platform.ExcludeFromCoverage
            |internal object BuildInfo {
            |    /** The CLI version (gradle.properties `ostromVersion`, or `-PostromVersion` in CI). */
            |    const val VERSION = "$version"
            |
            |    /** The usage statistics destination (`-PostromPosthogKey`), blank when the build has none. */
            |    const val POSTHOG_KEY = "$postHogKey"
            |}
            |""".trimMargin(),
        )
    }
}

kotlin {
    targets.withType<KotlinNativeTarget>().configureEach {
        binaries.executable {
            entryPoint = "dev.ostrom.cli.main"
            baseName = "ostrom"
        }
        binaries.configureEach {
            if (konanTarget.family == org.jetbrains.kotlin.konan.target.Family.LINUX && buildType.name == "DEBUG") {
                // Clikt 5.1.0 caches export the same internal symbol twice on Linux (seen in TeamCode's CLI).
                disableNativeCache(
                    version = DisableCacheInKotlinVersion.`2_4_21`,
                    reason = "Clikt 5.1.0 duplicate selfAndAncestors symbol in Linux static caches",
                )
            }
        }
    }
    sourceSets {
        commonMain {
            kotlin.srcDir(generateBuildInfo)
            dependencies {
                implementation(projects.platform)
                implementation(projects.hooks)
                implementation(projects.launcher)
                implementation(projects.mcp)
                implementation(projects.apiClient)
                implementation(libs.clikt)
                implementation(libs.coroutines.core)
                implementation(libs.serialization.json)
            }
        }
        commonTest.dependencies {
            implementation(libs.okio.fakefilesystem)
        }
    }
}
